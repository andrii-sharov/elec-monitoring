import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { resources, type Dictionary } from '../src/i18n/index.ts';

const order = ['uk', 'en', 'ru'] as const;
type Lang = (typeof order)[number];
type Tree = { [key: string]: string | Tree };

export function flattenSetup(dictionary: Dictionary): Record<string, string> {
  const out: Record<string, string> = {};
  const walk = (tree: Tree, prefix: string) => {
    for (const [key, value] of Object.entries(tree)) {
      const path = prefix ? `${prefix}.${key}` : key;
      if (typeof value === 'string') out[path] = value;
      else walk(value, path);
    }
  };
  walk(dictionary.device.setup as Tree, '');
  return out;
}

function fieldName(path: string): string {
  return path
    .split('.')
    .map((part, i) => (i === 0 ? part : part[0]!.toUpperCase() + part.slice(1)))
    .join('');
}

function escapeHtml(text: string): string {
  return text
    .replaceAll('&', '&amp;')
    .replaceAll('<', '&lt;')
    .replaceAll('>', '&gt;')
    .replaceAll('"', '&quot;');
}

function escapeC(text: string): string {
  return text.replaceAll('\\', '\\\\').replaceAll('"', '\\"').replaceAll('\n', '\\n');
}

export function renderHeader(dicts: Record<Lang, Record<string, string>>): string {
  const keys = Object.keys(dicts.en);
  for (const lang of order) {
    const missing = keys.filter((key) => dicts[lang][key] === undefined);
    if (missing.length > 0) throw new Error(`${lang} is missing ${missing.join(', ')}`);
  }

  const fields = keys.map((key) => `  const char* ${fieldName(key)};`).join('\n');
  const entries = order
    .map((lang) => {
      const values = keys.map((key) => `    "${escapeC(escapeHtml(dicts[lang][key]!))}",`);
      return `  {\n${values.join('\n')}\n  },`;
    })
    .join('\n');

  return `// Generated by \`npm run firmware:strings -w shared\`. Do not edit.
#pragma once

struct PortalStrings {
${fields}
};

constexpr const char* kPortalLanguages[3] = {"uk", "en", "ru"};

constexpr PortalStrings kPortalStrings[3] = {
${entries}
};
`;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const target = new URL('../../firmware/src/generated/portal_strings.h', import.meta.url);
  const header = renderHeader({
    uk: flattenSetup(resources.uk.translation),
    en: flattenSetup(resources.en.translation),
    ru: flattenSetup(resources.ru.translation),
  });
  writeFileSync(target, header);
}
